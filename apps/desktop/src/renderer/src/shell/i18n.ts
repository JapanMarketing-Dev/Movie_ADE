export const SHELL_DICT: Record<Lang, Record<SKey, string>> = { ja, en };

export function shellTranslate(lang: Lang, key: SKey, vars?: Record<string, string>): string {
  let s = SHELL_DICT[lang][key] ?? SHELL_DICT.ja[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export type ST = (key: SKey, vars?: Record<string, string>) => string;

export function useST(): ST {
  const lang = useContext(LangContext);
  return useCallback((key, vars) => shellTranslate(lang, key, vars), [lang]);
}
