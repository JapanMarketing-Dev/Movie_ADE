export type TKey = Key;
export const DICT: Record<Lang, Record<Key, string>> = { ja, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string>): string {
  let s = DICT[lang][key] ?? DICT.ja[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export const LangContext = createContext<Lang>('ja');

export function useT(): (key: Key, vars?: Record<string, string>) => string {
  const lang = useContext(LangContext);
  return (key, vars) => translate(lang, key, vars);
}
